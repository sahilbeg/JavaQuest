package jq.m09.messaging;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * A fresh in-memory H2 database for one test, with the tables already created.
 * "app" is the connection your code gets. "observer" is a second connection the checks use to look,
 * so they only see what your code has committed. The database disappears when both are closed.
 */
final class Databases implements AutoCloseable {

    /** The Rentals service's tables: the rentals themselves, and its outbox. */
    static final String RENTALS_SCHEMA = """
            CREATE TABLE rental (
                id         VARCHAR(20) PRIMARY KEY,
                rider_id   VARCHAR(20) NOT NULL,
                bike_id    VARCHAR(10) NOT NULL,
                bike_type  VARCHAR(10) NOT NULL,
                status     VARCHAR(10) NOT NULL,
                minutes    INT,
                fare_cents BIGINT
            );
            CREATE TABLE outbox (
                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_id    VARCHAR(40) NOT NULL UNIQUE,
                topic       VARCHAR(40) NOT NULL,
                message_key VARCHAR(40) NOT NULL,
                payload     VARCHAR(1000) NOT NULL,
                sent        BOOLEAN DEFAULT FALSE NOT NULL
            );
            """;

    /** The Billing service's own tables, in its own database. */
    static final String BILLING_SCHEMA = """
            CREATE TABLE processed_event (
                event_id VARCHAR(40) PRIMARY KEY
            );
            CREATE TABLE rider_bill (
                rider_id    VARCHAR(20) PRIMARY KEY,
                total_cents BIGINT NOT NULL,
                rides       INT NOT NULL
            );
            """;

    private static final AtomicInteger NEXT_NAME = new AtomicInteger();

    final Connection app;
    final Connection observer;

    private Databases(String schema) throws SQLException {
        String url = "jdbc:h2:mem:spoke-messaging-" + NEXT_NAME.incrementAndGet() + ";LOCK_TIMEOUT=200";
        observer = DriverManager.getConnection(url);
        app = DriverManager.getConnection(url);
        run(observer, schema);
    }

    static Databases rentals() throws SQLException {
        Databases dbs = new Databases(RENTALS_SCHEMA);
        run(dbs.observer, """
                INSERT INTO rental (id, rider_id, bike_id, bike_type, status) VALUES
                    ('rental-17', 'rider-7', 'B-1042', 'EBIKE', 'ACTIVE'),
                    ('rental-18', 'rider-9', 'B-2001', 'CLASSIC', 'ACTIVE'),
                    ('rental-19', 'rider-12', 'B-3001', 'CARGO', 'ACTIVE');
                INSERT INTO rental VALUES ('rental-12', 'rider-4', 'B-1042', 'EBIKE', 'ENDED', 10, 400);
                """);
        return dbs;
    }

    static Databases billing() throws SQLException {
        return new Databases(BILLING_SCHEMA);
    }

    static void run(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** Adds an outbox row straight away, the way RideEndService would. */
    static void addOutboxRow(Connection connection, String eventId, String riderId, boolean sent) throws SQLException {
        try (PreparedStatement insert = connection.prepareStatement(
                "INSERT INTO outbox (event_id, topic, message_key, payload, sent) VALUES (?, 'ride-events', ?, ?, ?)")) {
            insert.setString(1, eventId);
            insert.setString(2, riderId);
            insert.setString(3, new RideEnded(eventId, "rental-17", riderId, "B-1042", BikeType.EBIKE, 20, 700).toJson());
            insert.setBoolean(4, sent);
            insert.executeUpdate();
        }
    }

    /** The first column of every row, joined with ", ". */
    String text(String sql) throws SQLException {
        StringBuilder out = new StringBuilder();
        try (Statement statement = observer.createStatement(); ResultSet rows = statement.executeQuery(sql)) {
            while (rows.next()) {
                if (out.length() > 0) {
                    out.append(", ");
                }
                out.append(rows.getString(1));
            }
        }
        return out.toString();
    }

    /** Each row's columns joined with "|", rows joined with ", ". */
    String rows(String sql) throws SQLException {
        StringBuilder out = new StringBuilder();
        try (Statement statement = observer.createStatement(); ResultSet rows = statement.executeQuery(sql)) {
            int columns = rows.getMetaData().getColumnCount();
            while (rows.next()) {
                if (out.length() > 0) {
                    out.append(", ");
                }
                for (int c = 1; c <= columns; c++) {
                    if (c > 1) {
                        out.append('|');
                    }
                    out.append(rows.getString(c));
                }
            }
        }
        return out.toString();
    }

    @Override
    public void close() throws SQLException {
        app.close();
        observer.close();
    }
}
